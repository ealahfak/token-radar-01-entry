// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// A protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol). Live-token protocols are kept apart and shown at the market's own value, never mixed into
// the ranked board: the board ranks what does not trade yet.
//
// Implied value follows only from the snapshot's own ten fields, never from a list of names:
//
//   base       = tvl_usd x sector multiple (category is a snapshot field)
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.55 + min(age_days, 1460) / 1460 x 0.45   (age unknown: 0.70)
//   implied    = max(1, round(base x growthMult x maturity))
//
// age_days is how long the protocol has run with no token (snapshot as_of minus listed_at), so the
// maturity factor is the no-token runway: a protocol that has survived four years without a token is
// worth more of its TVL than one listed last month. Every multiplier is written into board.json and
// shown on the page, so the number is auditable row by row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_multiple: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.55,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_multiple: 0.7,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-3';

/** A comps multiple: dollars of market cap per dollar of TVL, read off the snapshot's own tokenized protocols. */
export interface Comps {
  global: { n: number; median: number };
  by_category: Record<string, { n: number; median: number }>;
  min_n: number;
}

